#!/usr/bin/env bash
#
# reduce.sh CASE_DIR [REF_TAG BAD_TAG] — shrink a saved fuzz finding with
# C-Reduce (or C-Vise) while the failure keeps reproducing.
#
#   CASE_DIR   a directory under tests/fuzz/work/findings/ (…-mismatch or …-crash)
#   REF_TAG    config that behaves correctly (default: the first OK config
#              whose CRC matches the majority)
#   BAD_TAG    config that misbehaves (default: the first config that differs)
#
# Tags are the first column of CASE_DIR/configs (e.g. attiny3217-Os).
# The result is CASE_DIR/reduce/program.c; the original is left untouched.
#
# The interestingness test rejects candidates that avr-gcc warns about in ways
# that usually mean C-Reduce introduced undefined behaviour (uninitialised
# reads, missing returns, implicit declarations, out-of-bounds constant
# indexes, ...). That filter is heuristic: before blaming simavr or avr-gcc,
# read the reduced program and confirm it is still well defined.
set -euo pipefail

FUZZ_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
case_dir=$(cd "${1:?usage: reduce.sh CASE_DIR [REF_TAG BAD_TAG]}" && pwd)
WORK=${WORK:-$FUZZ_DIR/work}
RUNNER=${RUNNER:-$WORK/csmith_runner}
MAX_CYCLES=${MAX_CYCLES:-200000000}
if [ -z "${CSMITH_INC:-}" ]; then
	CSMITH_INC=$(cd "$(dirname "$(readlink -f "$(command -v csmith)")")/../include" && pwd)
fi
[ -x "$RUNNER" ] || { echo "no runner at $RUNNER — run fuzz.sh once first" >&2; exit 1; }
[ -f "$case_dir/configs" ] || { echo "$case_dir/configs missing" >&2; exit 1; }

reducer=$(command -v creduce || command -v cvise || true)
[ -n "$reducer" ] || { echo "install creduce or cvise" >&2; exit 1; }

# Pick REF/BAD from the recorded results unless given.
out_status() { cut -d' ' -f1 "$case_dir/$1.out"; }
out_crc() { sed -n 's/.*crc=\([0-9a-f]*\).*/\1/p' "$case_dir/$1.out"; }
tags=$(cut -d' ' -f1 "$case_dir/configs")
ref=${2:-}
bad=${3:-}
if [ -z "$ref" ]; then
	major=$(for t in $tags; do out_crc "$t"; done | sed '/^$/d' | sort | uniq -c | sort -rn | awk 'NR==1{print $2}')
	for t in $tags; do
		[ "$(out_status "$t")" = OK ] && [ "$(out_crc "$t")" = "$major" ] && { ref=$t; break; }
	done
fi
if [ -z "$bad" ]; then
	for t in $tags; do
		[ "$t" = "$ref" ] && continue
		if [ "$(out_status "$t")" != OK ] || [ "$(out_crc "$t")" != "$(out_crc "$ref")" ]; then
			bad=$t; break
		fi
	done
fi
[ -n "$ref" ] && [ -n "$bad" ] || { echo "cannot pick REF/BAD configs; pass them explicitly" >&2; exit 1; }
cfg_of() { awk -v t="$1" '$1 == t { $1 = ""; sub(/^ /, ""); print }' "$case_dir/configs"; }
read -r ref_mcu ref_opt <<<"$(cfg_of "$ref")"
read -r bad_mcu bad_opt <<<"$(cfg_of "$bad")"
bad_status=$(out_status "$bad")
echo "reducing $case_dir: ref=$ref ($ref_mcu $ref_opt) bad=$bad ($bad_mcu $bad_opt, $bad_status)"

rd="$case_dir/reduce"
rm -rf "$rd"
mkdir -p "$rd"
cp "$case_dir/program.c" "$rd/program.c"

cat >"$rd/interesting.sh" <<EOF
#!/usr/bin/env bash
# C-Reduce interestingness test (generated by tests/fuzz/reduce.sh).
# Runs in a scratch copy containing program.c; exit 0 = still interesting.
set -u
grep -q '#include "csmith.h"' program.c || exit 1
grep -q 'platform_main_end' program.c || exit 1

UBWARN="-Wall -Wextra -Werror=uninitialized -Werror=maybe-uninitialized \\
  -Werror=return-type -Werror=implicit-function-declaration -Werror=implicit-int \\
  -Werror=int-conversion -Werror=incompatible-pointer-types -Werror=array-bounds \\
  -Werror=div-by-zero -Werror=shift-count-overflow -Werror=shift-count-negative \\
  -Werror=aggressive-loop-optimizations -Werror=sequence-point \\
  -Werror=int-to-pointer-cast -Werror=pointer-to-int-cast -Werror=address -Werror=main"
INC="-I $FUZZ_DIR/runtime -I $CSMITH_INC"

# Warning screen at -O2 so the uninitialised-use analysis actually runs.
avr-gcc -mmcu=$ref_mcu -O2 \$UBWARN \$INC -c -o /dev/null program.c >/dev/null 2>&1 || exit 1

build() { avr-gcc -mmcu=\$1 \$2 -w \$INC -ffunction-sections -fdata-sections \\
  -Wl,--gc-sections -o \$3 program.c $FUZZ_DIR/runtime/fuzz_main.c >/dev/null 2>&1; }
run() { local end; end=\$(avr-nm \$2 | awk '\$3 == "_end" { print \$1 }')
  timeout 60 $RUNNER \$1 \$2 \$end $MAX_CYCLES 2>/dev/null; }

build $ref_mcu "$ref_opt" ref.elf || exit 1
build $bad_mcu "$bad_opt" bad.elf || exit 1
r=\$(run $ref_mcu ref.elf); case "\$r" in OK*) ;; *) exit 1 ;; esac
b=\$(run $bad_mcu bad.elf)
case "$bad_status" in
OK)	case "\$b" in OK*) ;; *) exit 1 ;; esac
	rc=\${r#*crc=}; rc=\${rc%% *}; bc=\${b#*crc=}; bc=\${bc%% *}
	[ "\$rc" != "\$bc" ] || exit 1 ;;
*)	case "\$b" in $bad_status*) ;; *) exit 1 ;; esac ;;
esac
exit 0
EOF
chmod +x "$rd/interesting.sh"

(cd "$rd" && ./interesting.sh) || {
	echo "the original case is not interesting under the reduction test" >&2
	echo "(it may trip the UB-warning screen; inspect $rd/interesting.sh)" >&2
	exit 1
}
cd "$rd"
"$reducer" --n "$(nproc)" ./interesting.sh program.c
echo "reduced program: $rd/program.c ($(wc -l <program.c) lines)"
